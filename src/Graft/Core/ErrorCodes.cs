namespace Graft.Core;

/// <summary>
/// 仕様書16章のエラーコード。ユーザー操作に起因する失敗はすべてこの列挙で表現する。
/// </summary>
public enum ErrorCode
{
    /// <summary>ブロックが存在しない。</summary>
    E001,
    /// <summary>ヘッダの構文エラー。</summary>
    E002,
    /// <summary>SEARCH部が空。</summary>
    E003,
    /// <summary>summaryが未指定。</summary>
    E004,
    /// <summary>パッチが途中で切れている。</summary>
    E005,
    /// <summary>エスケープ規則の不整合。</summary>
    E006,
    /// <summary>パッチキュー内で同一ファイルのブロックが重複（16章の表には無いため追加）。</summary>
    E007,
    /// <summary>
    /// ブロックの本文を集めている途中で、閉じられないまま次のブロックの開始行が現れた
    /// （17章の表には無いため追加。実際の事故対応。PatchParser.BrokenBodyFailure参照）。
    /// E006（エスケープ規則の不整合）と役割を分ける理由は同メソッドのコメントを参照。
    /// </summary>
    E008,
    /// <summary>
    /// パッチ全体を囲む外側のMarkdownコードフェンスが、本文中の``` によって早まって
    /// 閉じられた可能性がある（16章の表には無いため追加。PatchScanner.Create参照）。
    /// AIがパッチ全体をバッククォート3個で囲み、かつ本文にも``` を含めてしまうと、
    /// 本文中の最初の``` が外側のフェンスを閉じたことになってしまう
    /// （CommonMarkのフェンス規則上、閉じフェンスは開始と同数以上のバッククォートで
    /// 成立するため）。これを黙って本文欠落のまま解析し続けるのではなく、ここで
    /// 打ち切って利用者に気づける形で失敗させる。
    /// </summary>
    E009,

    /// <summary>SEARCH部が見つからない。</summary>
    E101,
    /// <summary>複数箇所にマッチ。</summary>
    E102,
    /// <summary>終了アンカーが見つからない。</summary>
    E103,
    /// <summary>アンカー省略記法の範囲が閾値を超過（仕様書4.4の警告。16章の表には無いため追加）。</summary>
    E104,

    /// <summary>パスがルート外。</summary>
    E201,
    /// <summary>拡張子が未許可。</summary>
    E202,
    /// <summary>サイズ上限超過。</summary>
    E203,
    /// <summary>ファイルがロック中。</summary>
    E204,
    /// <summary>読み取り専用。</summary>
    E205,
    /// <summary>パス長が上限を超過。</summary>
    E206,
    /// <summary>同一パッチ内で旧パスを参照。</summary>
    E207,
    /// <summary>同一ファイルにFULL形式とSR形式が混在（16章の表には無いため追加）。</summary>
    E208,

    /// <summary>ベースハッシュ不一致。</summary>
    E301,
    /// <summary>適用済みパッチの再投入。</summary>
    E302,
    /// <summary>プロジェクト一致率が低い。</summary>
    E303,
    /// <summary>
    /// 「全件適用（All or Nothing）」の設定により、適用できないブロックが1件でもあったため
    /// 中止（16章の表には無いため追加）。実機不具合対応: 以前はここでE101等の個別ブロックの
    /// エラーだけが表示され、「設定のせいで中止された」ことが利用者に伝わらなかった
    /// （個々のブロックのエラーだけを見ると、あたかもそのブロック単体の問題であるかのように
    /// 誤解される）。このコードを使い、設定が原因であることと対処法（部分適用可への切り替え）を
    /// 明示する。個々のブロックのエラーは従来どおりissuesに含めて併記する
    /// （ApplyEngine.ApplyAsync参照）。
    /// </summary>
    E304,

    /// <summary>バックアップ作成失敗。</summary>
    E401,
    /// <summary>書き込み失敗。</summary>
    E402,
    /// <summary>前回の適用が未完了。</summary>
    E403,
    /// <summary>設定・履歴データの破損。</summary>
    E404,
    /// <summary>バックアップの実体が見つからない。</summary>
    E405,
    /// <summary>
    /// 設定画面で入力した値が保存前の検証に失敗（14章の即時反映方式。16章の表には無いため追加）。
    /// E404（設定・履歴データの破損）と検出ロジックは共有するが、E404は「不正値を既定値へ
    /// 差し替えて延命した」場合（読み込み時）に使うのに対し、こちらは「何も差し替えず、
    /// 直すまで保存を保留している」場合（保存前の即時検証）に使う。同じ文言を使い回すと
    /// 「データが壊れて再生成された」という誤った印象を与えてしまうため区別する
    /// （<see cref="Graft.Infra.SettingsStore.ValidateOnly"/>参照）。
    /// </summary>
    E406,
    /// <summary>
    /// データ保存先（ポータブル／ユーザーフォルダ）の移行に失敗（16章の表には無いため追加）。
    /// コピー・検証のいずれかに失敗した場合に使う。元データは消さないため復旧不要。
    /// </summary>
    E407,

    /// <summary>フック実行失敗。</summary>
    E501,
    /// <summary>フックのタイムアウト。</summary>
    E502,

    /// <summary>グローバルホットキーの登録に失敗（16章の表には無いため追加）。</summary>
    E601,
    /// <summary>クリップボード監視が利用できない（16章の表には無いため追加）。</summary>
    E602,

    /// <summary>ファイルの保存に失敗（v2.0 仕様書17章）。</summary>
    E701,
    /// <summary>ディスク上の変更と未保存編集が競合（v2.0 仕様書17章）。</summary>
    E702,
    /// <summary>バイナリまたは未対応形式のため開けない（v2.0 仕様書17章）。</summary>
    E703,
    /// <summary>ファイル監視の開始に失敗（v2.0 仕様書17章）。</summary>
    E704,
    /// <summary>クリップボードを取得できない（v2.1 仕様書17章）。</summary>
    E708,
    /// <summary>
    /// 日本語を表示できるフォントが見つからない（v2.1 仕様書2.5・17章）。UI/コードいずれの
    /// フォールバック列（Tokens.axaml）を辿っても、日本語グリフを1つも描画できる
    /// フォントが環境に存在しない場合に使う（Themes.JapaneseFontAvailability参照）。
    /// </summary>
    E705,
    /// <summary>
    /// この環境では利用できない機能（v2.1 仕様書17章）。IPlatformService.IsSupportedが
    /// falseの機能（トレイ常駐・自動起動など）を起動時に検出したことをログへ残すための
    /// 汎用コード。個別コードを持つ機能（ホットキー=E601、クリップボード監視=E602）は
    /// そちらを使うため対象外（Platform.PlatformDiagnosticsLogging.LogUnsupportedFeature参照）。
    /// </summary>
    E706,
    /// <summary>
    /// OSのハイコントラストモードを検出した（v2.1 仕様書9.3・17章）。9.3のとおりGraftは
    /// プラットフォームによらず同一の配色トークンを維持するため、検出してもテーマ辞書は
    /// 切り替えない（Themes.ThemeManagerのクラスコメント「v2.0のWPF版からの構成差分」参照）。
    /// あくまで検出できたという事実を診断用にログへ残すための汎用コード
    /// （ISystemThemeWatcher.TryReadIsHighContrast・Platform.PlatformDiagnosticsLogging.
    /// LogHighContrastIfDetected参照）。
    ///
    /// 【E707ではなくE709を使う理由】 附録B項目19のとおり、E707はデータディレクトリ書き込み
    /// 不可通知のフォールバック案（項目7）向けに一度予約されたが実装されないまま
    /// 「欠番」と正式に訂正されている（17章「E707 は欠番」の明文）。この欠番を別の用途へ
    /// 転用すると、附録Bの変更履歴（「なぜ欠番になったか」という経緯の記録）と矛盾し、
    /// 将来の読者を混乱させる。E708（クリップボード取得失敗）の次の空き番号としてE709を
    /// 使う。
    /// </summary>
    E709,

    /// <summary>
    /// プロジェクトペイン改善: 「場所を変更」で選んだフォルダが、既に別プロジェクトとして
    /// 登録済み（16章の表には無いため追加）。E201（パスが不正・プロジェクトが見つからない）と
    /// 混同しないよう分ける。
    /// </summary>
    E209,

    /// <summary>
    /// SEARCH/REPLACE対象のファイルが見つからない、またはこの環境から読み取れない
    /// （16章の表には無いため追加）。実機で「ネットワークドライブ上のプロジェクトで
    /// すべてのブロックがE101になる」という報告があり、その調査の過程で、DryRunPlanner側の
    /// 挙動として「対象がcheck.Exists==falseのとき、SEARCH/REPLACEの照合対象が空になり
    /// E101（SEARCH部が見つからない）になる」という表示上の問題が見つかった。この報告事案の
    /// 根本原因（なぜ実機でcheck.Existsがfalseになったのか）は本コード追加の時点では
    /// 未確定（LongPath.Extendedの\\?\プレフィックスが原因という当初の推定は、エディタでは
    /// 同じファイルを開けたという報告と矛盾するため撤回している。LongPath.csのクラスコメント
    /// 参照）。ただし表示上の問題自体（E101が「ファイルは読めたが中身が一致しない」という
    /// 意味に読めてしまうこと）は理由を問わず存在するため、「そもそもファイルを読めていない」
    /// 場合をE210として区別する対応は独立に有効と判断した。FULL形式（新規作成が正規の用途）や
    /// APPEND/PREPEND単独（同じく新規作成できる）はこの対象に含めない。同一ファイルに
    /// FULL形式が混在する場合（E208）はFULLが先に適用され、その結果に対してSEARCH/REPLACEが
    /// 解決される正規の経路のため、これもE210の対象にしない（DryRunPlanner.PlanFileTextBlocksAsync
    /// 参照）。
    /// </summary>
    E210,
}

