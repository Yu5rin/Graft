namespace Graft.Core;

/// <summary>
/// 仕様書16章のエラーコード。ユーザー操作に起因する失敗はすべてこの列挙で表現する。
/// </summary>
public enum ErrorCode
{
    /// <summary>ブロックが存在しない。</summary>
    E001,
    /// <summary>ヘッダの構文エラー。</summary>
    E002,
    /// <summary>SEARCH部が空。</summary>
    E003,
    /// <summary>summaryが未指定。</summary>
    E004,
    /// <summary>パッチが途中で切れている。</summary>
    E005,
    /// <summary>エスケープ規則の不整合。</summary>
    E006,
    /// <summary>パッチキュー内で同一ファイルのブロックが重複（16章の表には無いため追加）。</summary>
    E007,
    /// <summary>
    /// ブロックの本文を集めている途中で、閉じられないまま次のブロックの開始行が現れた
    /// （17章の表には無いため追加。実際の事故対応。PatchParser.BrokenBodyFailure参照）。
    /// E006（エスケープ規則の不整合）と役割を分ける理由は同メソッドのコメントを参照。
    /// </summary>
    E008,
    /// <summary>
    /// パッチ全体を囲む外側のMarkdownコードフェンスが、本文中の``` によって早まって
    /// 閉じられた可能性がある（16章の表には無いため追加。PatchScanner.Create参照）。
    /// AIがパッチ全体をバッククォート3個で囲み、かつ本文にも``` を含めてしまうと、
    /// 本文中の最初の``` が外側のフェンスを閉じたことになってしまう
    /// （CommonMarkのフェンス規則上、閉じフェンスは開始と同数以上のバッククォートで
    /// 成立するため）。これを黙って本文欠落のまま解析し続けるのではなく、ここで
    /// 打ち切って利用者に気づける形で失敗させる。
    /// </summary>
    E009,
    /// <summary>
    /// 標準SEARCH/REPLACE形式（5.2）で、ファイルの本文の中にパッチの記号（&lt;&lt;&lt;&lt;&lt;&lt;&lt; SEARCH・
    /// &gt;&gt;&gt;&gt;&gt;&gt;&gt; END_FILE 等）が含まれているため、どこまでがファイルの中身か判別できない
    /// （16章の表には無いため追加。実機で起きた事故への対応。StandardSearchReplaceAdapter.Parse参照）。
    ///
    /// 【E006・E008・E009と別にする理由】E006・E008は Graft独自形式（4.9）の本文収集で、E009は外側の
    /// コードフェンスで起きる別の問題であり、対処（エスケープ・囲みの4個化）が異なる。標準SR形式には
    /// エスケープ規則が無く、本文の終端は「最初に現れた終了マーカー」で決まるため、本文に終了マーカーが
    /// 現れると黙って途切れ、残りがまったく別のブロックとして読まれる。この状態を放置すると
    /// 最終的にE303（プロジェクト一致率0%）のような無関係なエラーになり、利用者が原因に辿り着けなかった。
    /// 番号は0xx台（パッチの構文）の空き番号。
    /// </summary>
    E010,

    /// <summary>SEARCH部が見つからない。</summary>
    E101,
    /// <summary>複数箇所にマッチ。</summary>
    E102,
    /// <summary>終了アンカーが見つからない。</summary>
    E103,
    /// <summary>アンカー省略記法の範囲が閾値を超過（仕様書4.4の警告。16章の表には無いため追加）。</summary>
    E104,
    /// <summary>
    /// 同じファイルに対する複数のペアで、SEARCH部が置き換える行の範囲が重なっている、または
    /// まったく同じペアが重複している（16章の表には無いため追加。BlockResolver.RejectOverlappingEdits参照）。
    /// E101〜E104は「1つのペアが元のファイルに当たるか」の失敗であり、これは「当たった複数のペアが
    /// 互いに両立しない」という別の失敗のため、同じ1xx帯の空き番号E105を使う。
    /// </summary>
    E105,

    /// <summary>パスがルート外。</summary>
    E201,
    /// <summary>拡張子が未許可。</summary>
    E202,
    /// <summary>サイズ上限超過。</summary>
    E203,
    /// <summary>ファイルがロック中。</summary>
    E204,
    /// <summary>読み取り専用。</summary>
    E205,
    /// <summary>パス長が上限を超過。</summary>
    E206,
    /// <summary>同一パッチ内で旧パスを参照。</summary>
    E207,
    /// <summary>同一ファイルにFULL形式とSR形式が混在（16章の表には無いため追加）。</summary>
    E208,

    /// <summary>ベースハッシュ不一致。</summary>
    E301,
    /// <summary>適用済みパッチの再投入。</summary>
    E302,
    /// <summary>プロジェクト一致率が低い。</summary>
    E303,
    /// <summary>
    /// 「全件適用（All or Nothing）」の設定により、適用できないブロックが1件でもあったため
    /// 中止（16章の表には無いため追加）。実機不具合対応: 以前はここでE101等の個別ブロックの
    /// エラーだけが表示され、「設定のせいで中止された」ことが利用者に伝わらなかった
    /// （個々のブロックのエラーだけを見ると、あたかもそのブロック単体の問題であるかのように
    /// 誤解される）。このコードを使い、設定が原因であることと対処法（部分適用可への切り替え）を
    /// 明示する。個々のブロックのエラーは従来どおりissuesに含めて併記する
    /// （ApplyEngine.ApplyAsync参照）。
    /// </summary>
    E304,
    /// <summary>
    /// このパッチを適用すると、そのファイルの内容が過去のリビジョンの適用後の内容と
    /// 同じになる（16章の表には無いため追加。DryRunPlanner.CheckDuplicateAsync参照）。
    /// AIは、利用者が一度適用した変更をもう一度出してくることがある。そのとき本文を
    /// 少し書き換える（summaryの文言を変える、SR形式をFULL形式に書き直す、ブロックの
    /// 順序を入れ替える等）ため、パッチ本文のハッシュが変わってしまい、E302では捕まえられ
    /// ない。利用者から見れば「結局、前に適用したのと同じ状態になる」だけなので、
    /// 適用前にそのことへ気づけるようにする。
    /// <para>
    /// 【E302との役割分担】 E302は「パッチ本文」のハッシュの完全一致を見る（書き方まで
    /// 同じ）。E305は「適用後のファイル内容」のハッシュの一致を見る（書き方は違っても
    /// 結果が同じ）。同じパッチが両方に当たるときは、E302のほうが強い（かつ既定で適用を
    /// 止める）ので、E305は出さない。
    /// </para>
    /// <para>
    /// 常に警告（Warning）で、適用は止めない。パッチが間違っているとは限らず、たとえば
    /// 巻き戻した内容をもう一度戻すような正当な操作も同じ形になるため。
    /// </para>
    /// </summary>
    E305,

    /// <summary>バックアップ作成失敗。</summary>
    E401,
    /// <summary>書き込み失敗。</summary>
    E402,
    /// <summary>前回の適用が未完了。</summary>
    E403,
    /// <summary>設定・履歴データの破損。</summary>
    E404,
    /// <summary>バックアップの実体が見つからない。</summary>
    E405,
    /// <summary>
    /// 設定画面で入力した値が保存前の検証に失敗（14章の即時反映方式。16章の表には無いため追加）。
    /// E404（設定・履歴データの破損）と検出ロジックは共有するが、E404は「不正値を既定値へ
    /// 差し替えて延命した」場合（読み込み時）に使うのに対し、こちらは「何も差し替えず、
    /// 直すまで保存を保留している」場合（保存前の即時検証）に使う。同じ文言を使い回すと
    /// 「データが壊れて再生成された」という誤った印象を与えてしまうため区別する
    /// （<see cref="Graft.Infra.SettingsStore.ValidateOnly"/>参照）。
    /// </summary>
    E406,
    /// <summary>
    /// データ保存先（ポータブル／ユーザーフォルダ）の移行に失敗（16章の表には無いため追加）。
    /// コピー・検証のいずれかに失敗した場合に使う。元データは消さないため復旧不要。
    /// </summary>
    E407,

    /// <summary>フック実行失敗。</summary>
    E501,
    /// <summary>フックのタイムアウト。</summary>
    E502,

    /// <summary>グローバルホットキーの登録に失敗（16章の表には無いため追加）。</summary>
    E601,
    /// <summary>クリップボード監視が利用できない（16章の表には無いため追加）。</summary>
    E602,

    /// <summary>ファイルの保存に失敗（v2.0 仕様書17章）。</summary>
    E701,
    /// <summary>ディスク上の変更と未保存編集が競合（v2.0 仕様書17章）。</summary>
    E702,
    /// <summary>バイナリまたは未対応形式のため開けない（v2.0 仕様書17章）。</summary>
    E703,
    /// <summary>ファイル監視の開始に失敗（v2.0 仕様書17章）。</summary>
    E704,
    /// <summary>クリップボードを取得できない（v2.1 仕様書17章）。</summary>
    E708,
    /// <summary>
    /// 日本語を表示できるフォントが見つからない（v2.1 仕様書2.5・17章）。UI/コードいずれの
    /// フォールバック列（Tokens.axaml）を辿っても、日本語グリフを1つも描画できる
    /// フォントが環境に存在しない場合に使う（Themes.JapaneseFontAvailability参照）。
    /// </summary>
    E705,
    /// <summary>
    /// この環境では利用できない機能（v2.1 仕様書17章）。IPlatformService.IsSupportedが
    /// falseの機能（トレイ常駐・自動起動など）を起動時に検出したことをログへ残すための
    /// 汎用コード。個別コードを持つ機能（ホットキー=E601、クリップボード監視=E602）は
    /// そちらを使うため対象外（Platform.PlatformDiagnosticsLogging.LogUnsupportedFeature参照）。
    /// </summary>
    E706,
    /// <summary>
    /// OSのハイコントラストモードを検出した（v2.1 仕様書9.3・17章）。9.3のとおりGraftは
    /// プラットフォームによらず同一の配色トークンを維持するため、検出してもテーマ辞書は
    /// 切り替えない（Themes.ThemeManagerのクラスコメント「v2.0のWPF版からの構成差分」参照）。
    /// あくまで検出できたという事実を診断用にログへ残すための汎用コード
    /// （ISystemThemeWatcher.TryReadIsHighContrast・Platform.PlatformDiagnosticsLogging.
    /// LogHighContrastIfDetected参照）。
    ///
    /// 【E707ではなくE709を使う理由】 附録B項目19のとおり、E707はデータディレクトリ書き込み
    /// 不可通知のフォールバック案（項目7）向けに一度予約されたが実装されないまま
    /// 「欠番」と正式に訂正されている（17章「E707 は欠番」の明文）。この欠番を別の用途へ
    /// 転用すると、附録Bの変更履歴（「なぜ欠番になったか」という経緯の記録）と矛盾し、
    /// 将来の読者を混乱させる。E708（クリップボード取得失敗）の次の空き番号としてE709を
    /// 使う。
    /// </summary>
    E709,
    /// <summary>
    /// AIが「SEARCHを正確に作れないので情報が足りない」と申告した（v2.1 仕様書5.2・17章）。
    /// 運用規定では、AIはSEARCH部を正確に作れない場合に
    /// 「<c>NEED_MORE_CONTEXT: &lt;ファイルパス&gt;</c>」の行だけ（必要なファイルごとに1行。
    /// パス無しの語だけも可）を返す。これを黙ってE001（ブロックが存在しない）と
    /// して扱うと、利用者には「AIが変な出力をした」としか見えず、実際には
    /// 「AIが情報不足を訴えているので、対象ファイルを渡し直せば解決する」という
    /// 全く別の状況であることが伝わらないため、専用のコードで区別する
    /// （<see cref="StandardSearchReplaceAdapter.TryParseNeedMoreContext"/>参照）。
    /// 求められたファイルは <see cref="GraftIssue.RequestedPaths"/> に入り、コンテキスト収集の
    /// 選択へそのまま反映できる。
    ///
    /// 【E707ではなくE710を使う理由】 附録B項目19のとおりE707は「欠番」と正式に訂正されている
    /// （17章「E707 は欠番」の明文）。欠番を別用途へ転用すると附録Bの経緯の記録と矛盾するため、
    /// E709の次の空き番号としてE710を使う（E709と同じ判断）。
    /// </summary>
    E710,

    /// <summary>
    /// プロジェクトペイン改善: 「場所を変更」で選んだフォルダが、既に別プロジェクトとして
    /// 登録済み（16章の表には無いため追加）。E201（パスが不正・プロジェクトが見つからない）と
    /// 混同しないよう分ける。
    /// </summary>
    E209,

    /// <summary>
    /// SEARCH/REPLACE対象のファイルが見つからない、またはこの環境から読み取れない
    /// （16章の表には無いため追加）。実機で「ネットワークドライブ上のプロジェクトで
    /// すべてのブロックがE101になる」という報告があり、その調査の過程で、DryRunPlanner側の
    /// 挙動として「対象がcheck.Exists==falseのとき、SEARCH/REPLACEの照合対象が空になり
    /// E101（SEARCH部が見つからない）になる」という表示上の問題が見つかった。この報告事案の
    /// 根本原因（なぜ実機でcheck.Existsがfalseになったのか）は本コード追加の時点では
    /// 未確定（LongPath.Extendedの\\?\プレフィックスが原因という当初の推定は、エディタでは
    /// 同じファイルを開けたという報告と矛盾するため撤回している。LongPath.csのクラスコメント
    /// 参照）。ただし表示上の問題自体（E101が「ファイルは読めたが中身が一致しない」という
    /// 意味に読めてしまうこと）は理由を問わず存在するため、「そもそもファイルを読めていない」
    /// 場合をE210として区別する対応は独立に有効と判断した。FULL形式（新規作成が正規の用途）や
    /// APPEND/PREPEND単独（同じく新規作成できる）はこの対象に含めない。同一ファイルに
    /// FULL形式が混在する場合（E208）はFULLが先に適用され、その結果に対してSEARCH/REPLACEが
    /// 解決される正規の経路のため、これもE210の対象にしない（DryRunPlanner.PlanFileTextBlocksAsync
    /// 参照）。
    /// </summary>
    E210,

    /// <summary>
    /// v1.0.15 セキュリティ対応: バージョン管理システムの内部フォルダ（<c>.git</c>・<c>.hg</c>・
    /// <c>.svn</c>）の配下へ書き込もうとした（16章の表には無いため追加）。
    ///
    /// 【なぜ専用のコードを作ったか】 <c>.git</c> はプロジェクトルートの「内側」にあるため、
    /// E201（パスがルート外）を流用すると、利用者には「ルート外だと言われたが、どう見ても
    /// ルート内にある」としか読めず、何が起きたのかが伝わらない。拒否の理由が
    /// 「ルートから出ようとしたから」ではなく「そこはバージョン管理の内部だから」である以上、
    /// 別のコードで区別する必要がある。
    ///
    /// 【なぜ拒否するのか】 <c>.git/config</c> に書かれた <c>core.fsmonitor</c> 等の設定値は
    /// gitがコマンドとして実行し、<c>.git/hooks/*</c> はコミット等のたびに自動実行される。
    /// Graftは<c>editor.gitGutter</c>が既定オンで、プロジェクトルートを作業ディレクトリとして
    /// gitを起動するため（<see cref="Graft.Features.GitIntegration"/>）、ここへ書けることは
    /// 実質的に任意コード実行と同義になる（<see cref="PathGuard"/>の該当判定のコメント参照）。
    ///
    /// 【E707ではなくE211を使う理由】 附録B項目19のとおりE707は「欠番」と正式に訂正されている
    /// （17章「E707 は欠番」の明文）。欠番を別用途へ転用すると附録Bの経緯の記録と矛盾するため
    /// 使わない（E709・E710と同じ判断）。パスに関するエラーは2xx台にまとまっているので、
    /// その空き番号であるE211を使う。
    /// </summary>
    E211,

    /// <summary>
    /// v1.0.15 セキュリティ対応: パスの構成要素に、ファイル名として使用できない文字
    /// （<c>:</c>）が含まれている（16章の表には無いため追加）。
    ///
    /// 【なぜ専用のコードを作ったか】 Windowsの代替データストリーム記法
    /// （<c>evil.exe:payload.txt</c>）を使うと、<c>Path.GetExtension</c> が <c>".txt"</c> を
    /// 返すため拡張子ホワイトリストを回避できることを実測で確認した。これはE202
    /// （拡張子が未許可）でもE201（ルート外）でもなく、「そもそもパスの書き方として不正」で
    /// あり、対処も「設定で許可できます」（E202の対処文）ではなく「ファイル名から <c>:</c> を
    /// 取り除く」になる。文言が食い違うため区別する（<see cref="PathGuard"/>の該当判定の
    /// コメント参照）。
    /// </summary>
    E212,

    /// <summary>
    /// 登録済みプロジェクトのルートフォルダが起動時に見つからず、未接続にした
    /// （16章の表には無いため追加。<see cref="Graft.Features.ProjectStore.ValidateAsync"/>参照）。
    ///
    /// 【なぜ専用コードを足したか】 以前はこの状況にE404（設定・履歴データの破損）を使っており、
    /// 実機では「E404 設定・履歴データの破損（…/missingproj）：プロジェクト「missingproj」の
    /// ルート（…）が見つからないため未接続にしました。」と表示されていた。フォルダを別の場所へ
    /// 移動した／ネットワークドライブが未接続、というだけで何も壊れていないのに「データの破損」と
    /// 告げられ、しかもE404の対処文は「退避のうえ再生成しました」で、この状況にまったく
    /// 当てはまらない。利用者は設定や履歴が失われたと誤解する。E404は本来
    /// 「JSONが壊れていたので退避して作り直した」場合（<see cref="Graft.Infra.JsonFileStore"/>）
    /// のためのコードであり、そちらの意味を保つためにも分離した。
    ///
    /// 【E707ではなくE213を使う理由】 附録B項目19のとおりE707は「欠番」と正式に訂正されている
    /// （17章「E707 は欠番」の明文）。欠番を転用すると附録Bの経緯の記録と矛盾する。この不具合は
    /// 「パスの問題」であり、パス系のE2xx帯へ置くのが素直なため、E211・E212（いずれも
    /// v1.0.15のセキュリティ対応で先に埋まった）の次の空き番号としてE213を使う。
    /// </summary>
    E213,

    /// <summary>
    /// 異常系点検「低」4件目の対応: 新規作成・名前の変更で渡された「ファイル名/フォルダ名
    /// 1つ分」が不正（パス区切りを含む・使用できない文字を含む・制御文字を含む・
    /// 末尾が空白/ピリオド・長すぎる、のいずれか。16章の表には無いため追加）。
    /// E201（パスがルート外）はプロジェクトルートに対する相対パス全体の検証結果に使うのに
    /// 対し、こちらは「ちょうど1階層の名前」という、より狭い入力単体の検証結果に使う
    /// （<see cref="Features.FileTreeService"/>参照）。E211（バージョン管理の内部フォルダ）・
    /// E212（使用できない文字 <c>:</c>）・E213（プロジェクトのフォルダが見つからない）は
    /// いずれも別件の検証のため、番号が連続して見えるが対応する不具合は別々である
    /// （本コードは空き番号のE214を使う）。
    /// </summary>
    E214,

    /// <summary>
    /// セキュリティ点検（v1.0.15）指摘対応: 書き込み先がデータ保存先
