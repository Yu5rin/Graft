namespace Graft.Core;

/// <summary>
/// Markdownプレビュー機能の性能ガード（利用者指示の追加要件6）。
///
/// 【なぜ必要か】
/// MarkdownをAvalonia標準コントロール（<see cref="Graft.Views.ManualMarkdownRenderer"/>）へ
/// 丸ごと展開する方式は、見出し・段落・表・コードブロックの1個1個が独立したUI要素
/// （<c>SelectableTextBlock</c>・<c>Border</c>・<c>Grid</c>等）になるため、巨大なファイルでは
/// 「行数に比例したUI要素をまとめて生成する」コストがそのまま重くなる
/// （AvaloniaEditの仮想化＝可視行のみ処理、とは根本的に方式が異なる）。
///
/// 【判定方法】
/// パース前に分かる安価な指標（文字数・行数）だけで判定する。実際にMarkdownをパースして
/// ブロック数を数えるには結局パースが必要になり、「重い処理を避けるための判定」自体が
/// 重くなってしまうため、パースを経ない指標にしている。
///
/// 【しきい値の根拠（実測）】
/// 初版（見出し・段落・箇条書き・太字・インラインコード・リンクのみ対応）は
/// <see cref="Graft.Views.ManualMarkdownRenderer.Render"/>を直接呼び、見出し＋段落を交互に
/// 並べたMarkdown（1ペアで2行・2ブロック）のレンダリング時間をヘッドレス環境で実測して
/// 決めていた（ウォームアップ1回の後に計測。UIツリーへの追加・レイアウトは含まない、パース＋
/// コントロール構築のみの時間）。
///
/// <code>
/// ブロック数    文字数      経過時間
///   2,000       68,780件    125.0ms
///   4,000      139,780件    283.2ms
///  10,000      352,780件    414.0ms
///  20,000      707,780件    701.1ms
///  40,000    1,437,780件  1,472.5ms
/// </code>
///
/// 【GitHub形式の基本記法拡張後の再実測】
/// 斜体・打ち消し線・引用（再帰的なブロック解析）・画像・箇条書きの入れ子・脚注・見出し6段階を
/// 追加し、インライン記法の解析を正規表現の単純な非重複マッチから1文字ずつ読み進める手書きの
/// 字句解析（<see cref="Graft.Views.ManualMarkdownRenderer"/>クラスコメント参照）へ作り直した
/// ことで、文字あたりの処理コストが初版よりおよそ2〜3倍に増えた（画像・脚注参照の判定、
/// 区切り文字スタックでの強調解決、リンク・画像の括弧対応付けなどが増えたぶん）。
/// 見出し・段落（**強調**/*斜体*/~~打ち消し~~/`コード`/リンク/画像を含む）・箇条書き＋子項目を
/// 繰り返す構成で再実測（ウォームアップ1回の後、同一プロセス内で複数回計測。他条件は初版と同じ）:
///
/// <code>
/// 文字数        行数     経過時間
///  20,068         846      61.4ms
///  50,080       2,076     172.7ms
/// 100,100       4,126     341.2ms
/// 150,025       6,126     381.5ms
/// </code>
///
/// 文字数に対しほぼ線形（2乗的な劣化は見られない。線形性そのものの回帰確認は
/// tests/Graft.UiTests/MarkdownPreviewPerformanceTests.cs）。ただし同じ文字数あたりの時間が
/// 初版よりかかるようになった分、「プレビューに切り替えた瞬間にUIが固まる」体感を避けたいという
/// 初版の意図を保つため、しきい値そのものを引き下げた。
///
/// 具体的なしきい値:
/// - 文字数: <see cref="CharLimit"/>（10万文字。初版の15万文字から引き下げ）。上の実測で
///   約340ms程度に収まる規模。実際の画面表示ではこの後にAvalonia側のレイアウト・初回描画の
///   コストが追加で乗るため、初版と同じ考え方で実測値からさらに余裕を持たせている。
/// - 行数: <see cref="LineLimit"/>（6,000行。初版の8,000行から引き下げ）。1行あたり平均文字数が
///   短い（表・箇条書き中心）ファイルは文字数のしきい値だけでは検出できないため、ブロック数の
///   おおまかな上限として行数も別途チェックする（1ブロックが複数行にまたがる場合もあるため、
///   実際のブロック数はこれより少なくなるのが普通で、安全側の上限として機能する）。
///
/// どちらか一方でも超えたら、プレビューを諦めて編集モードで開く
/// （<see cref="Graft.ViewModels.EditorTabViewModel"/>のコンストラクタ参照）。
/// </summary>
public static class MarkdownPreviewSizeGuard
{
    /// <summary>プレビュー対象とする文字数の上限。超えると編集モードで開く。</summary>
    public const int CharLimit = 100_000;

    /// <summary>プレビュー対象とする行数の上限。超えると編集モードで開く。</summary>
    public const int LineLimit = 6_000;

    /// <summary>
    /// プレビューが利用できない場合、利用者へ表示する理由（日本語）を返す。
    /// 上限内であれば null（プレビュー可能）を返す。
    /// </summary>
    public static string? EvaluateUnavailableReason(int textLength, int lineCount)
    {
        if (textLength > CharLimit)
        {
            return $"ファイルが大きいため（約{textLength:N0}文字）、プレビューを表示せず編集モードで開いています。";
        }

        if (lineCount > LineLimit)
        {
            return $"ファイルが大きいため（{lineCount:N0}行）、プレビューを表示せず編集モードで開いています。";
        }

        return null;
    }
}
